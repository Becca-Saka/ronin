"""
Main execution module for the AI-driven mobile E2E testing agent.

This module coordinates:
1. Connecting to the mobile device (Android/iOS) via Appium.
2. Perceiving the screen using YOLOv8 (element detection) and EasyOCR (text extraction).
3. Querying Gemini (via LiteLLM/OpenRouter) to generate a high-level task plan.
4. Planning precise coordinate-based UI actions (taps, typing, etc.) based on the plan.
5. Executing those actions programmatically on the mobile device.
"""

import io
import json
import os
import time
from pathlib import Path

from dotenv import load_dotenv
from pydantic import BaseModel, Field

from actuation.actions import ActionPlan
from actuation.orchestrator import ActionOrchestrator
from device.device_session import DeviceSession
from llm.llm_client import LLMClient
from llm.messages import ImageMessage, Message
from perception.perception import ScreenPerception

# Load environment variables from .env
load_dotenv()

_MODEL = "openrouter/google/gemini-2.5-flash"
assets_dir = Path("assets")
goal = "I want to sign in to the app with email 'test@email.com'"



class TaskAction(BaseModel):
    """Represents a high-level logical step generated by the LLM planner."""
    action: str = Field(..., description="The action to perform")
    step: int = Field(..., description="The step number")
    description: str = Field(..., description="The description of the action")
    reason: str = Field(..., description="The reason for the action")


class TaskPlan(BaseModel):
    """Wrapper containing a list of high-level logical TaskActions."""
    actions: list[TaskAction] = Field(
        ..., description="The sequence of actions to perform"
    )


def format_elements_for_prompt(elements) -> str:
    """Formats detected GUI elements into a text description for LLM consumption.

    Args:
        elements: A list of GUIElement detected on the screen.

    Returns:
        A formatted string description listing each element type, text, and center coordinates.
    """
    lines = []
    for el in elements:
        cx = (el.bounding_box.x_min + el.bounding_box.x_max) // 2
        cy = (el.bounding_box.y_min + el.bounding_box.y_max) // 2
        if el.text:
            lines.append(f"- {el.element} | text: '{el.text}' | center: ({cx}, {cy})")
        else:
            lines.append(f"- {el.element} | center: ({cx}, {cy})")
    return "\n".join(lines)


def main():
    """Main function executing the perception-planning-actuation loop."""
    api_key = os.getenv("OPENROUTER_API_KEY")
    if not api_key:
        raise EnvironmentError("OPENROUTER_API_KEY is not set")
    os.environ["OPENROUTER_API_KEY"] = api_key

    device_name = "Pixel_8a"
    app_path = "example/testing_app/build/app/outputs/flutter-apk/app-debug.apk"

    llm = LLMClient(model=_MODEL)



    session = DeviceSession(
        device_name,
        app_path,
        record_session=True,
        session_dir=assets_dir,
    )
    try:
        device_control = session.start(is_headless=True)
        perception = ScreenPerception(session)
        gui_elements, annotated_img = perception.perceive()

        assets_dir.mkdir(parents=True, exist_ok=True)
        clean_timestamp = time.strftime("%Y%m%d_%H%M%S")
        filepath = assets_dir / f"annotated_img_{clean_timestamp}.png"
        annotated_img.save(filepath)
        print(f"  ↳ saved → {filepath}")

        for el in gui_elements:
            print(
                f"{el.element:20} {el.text:20} {el.confidence:20} {str(el.bounding_box):20} {el.type:20}"
            )

        buf = io.BytesIO()
        annotated_img.save(buf, format="PNG")
        annotated_img_bytes = buf.getvalue()

        print("Generating task plan...")
        task_plan: TaskPlan = llm.generate_response(
            [
                ImageMessage(
                    text=f"""You are an action planner for a task user wants to perform on an app.
Using the image attached, convert the user raw instruction into a precise sequence of actions needed to complete the task.

### User Task
"{goal}"
""",
                    png_bytes=annotated_img_bytes,
                )
            ],
            TaskPlan,
        )
        print(f"Got task plan: {task_plan}")

        actions: ActionPlan = llm.generate_response(
            [
                ImageMessage(
                    text=f"""You are an action planner. Convert the user task into a precise sequence of UI actions.

### User Task
{json.dumps([action.model_dump() for action in task_plan.actions])}

### UI Elements (element | text | center coordinates)
{format_elements_for_prompt(gui_elements)}

### Instructions
1. Identify which elements are needed for the task using their center coordinates.
2. Generate exactly the actions needed to complete the task — no more, no less.
3. Do NOT repeat the same action consecutively unless the task genuinely requires it.
""",
                    png_bytes=annotated_img_bytes,
                )
            ],
            ActionPlan,
        )
        print(f"Got actions: {actions}")

        print("Executing Actions...")
        ActionOrchestrator(device_control).orchestrate(actions)
        time.sleep(3)
        print("Task completed successfully!")

    finally:
        session.close()


if __name__ == "__main__":
    main()
