"""
RoninPlanner class managing prompt generation and closed-loop ReAct planning via the LLM.
"""

import json
import logging
from typing import List, Literal, Optional

from pydantic import BaseModel, Field

from actuation.actions import ActionPlan, CapabilityType, CAPABILITY_SCHEMAS
from llm.llm_client import LLMClient
from llm.messages import MultiPartMessage
from ronin_testing.models import QAIssue, RuleVerification
from utils.redactor import redact_elements, redact_text


logger = logging.getLogger(__name__)


class AgentStepResponse(BaseModel):
    """Represents a single decision step generated by the ReAct planner, including QA audits."""
    is_done: bool = Field(
        ...,
        description="Set to True if the test scenario instructions are fully completed or a critical failure occurs, otherwise False."
    )
    reasoning: str = Field(
        ...,
        description="Reasoning explaining the current screen state, QA audit evaluations, and the chosen action."
    )
    action: Optional[ActionPlan] = Field(
        None,
        description="The ActionPlan (containing exactly one action) to perform next. Must be None if is_done is True."
    )
    current_screen: str = Field(
        ...,
        description="The descriptive name of the current screen/page (e.g., 'Login Screen', 'Product Detail Screen')."
    )
    rule_verifications: List[RuleVerification] = Field(
        default_factory=list,
        description="Evaluations of the scenario expected outcomes and custom security rules against the current screen."
    )
    detected_issues: List[QAIssue] = Field(
        default_factory=list,
        description="List of detected visual bugs, layout overflows, crashed screens, or security data exposures found on the screen."
    )
    is_scenario_feasible: bool = Field(
        True,
        description="Set to False if the test scenario instructions are invalid/irrelevant for the current screen context (e.g. references missing input fields, tabs or buttons that cannot be accessed). Otherwise True."
    )
    infeasibility_reason: Optional[str] = Field(
        None,
        description="The detailed reason/explanation if the scenario is determined to be infeasible, otherwise None."
    )


class RoninPlanner:
    """Manages AI-driven visual and logical closed-loop planning for mobile automation."""

    def __init__(self, llm_client: LLMClient, use_multimodal_vision: bool = False):
        """Initializes the RoninPlanner.

        Args:
            llm_client: The LLMClient instance to use for completion requests.
            use_multimodal_vision: If True, allows the LLM to override element coordinates.
        """
        self.llm = llm_client
        self.use_multimodal_vision = use_multimodal_vision

    def _format_elements_for_prompt(self, elements) -> str:
        """Formats detected GUI elements into a text description for LLM consumption."""
        lines = []
        for el in elements:
            cx = (el.bounding_box.x_min + el.bounding_box.x_max) // 2
            cy = (el.bounding_box.y_min + el.bounding_box.y_max) // 2
            if el.text:
                lines.append(f"- {el.element} | text: '{el.text}' | center: ({cx}, {cy})")
            else:
                lines.append(f"- {el.element} | center: ({cx}, {cy})")
        return "\n".join(lines)

    def plan_next_step(
        self,
        goal: List[str] | str,
        expected_outcomes: List[str] = None,
        security_rules: List[str] = None,
        gui_elements = None,
        current_image_bytes: bytes = b"",
        visual_history: List[bytes] = None,
        text_history: List[str] = None,
        loop_warning: Optional[str] = None,
        drift_warning: Optional[str] = None,
    ) -> AgentStepResponse:
        """Generates the next logical step and action in the closed-loop ReAct sequence, evaluating QA rules.

        Args:
            goal: High-level instructions (or a legacy goal string) for the E2E test.
            expected_outcomes: List of expected assertions to verify.
            security_rules: List of security compliance rules to enforce.
            gui_elements: Detected elements on the current screen.
            current_image_bytes: Current screenshot image bytes.
            visual_history: List of past screenshot image bytes.
            text_history: List of previously executed actions as strings.
            loop_warning: Optional warning string if the agent is detected to be repeating actions.

        Returns:
            An AgentStepResponse indicating if the task is done, screen context, rule verifications, issues, and the next ActionPlan.
        """
        # Normalize input to support legacy goals
        if isinstance(goal, str):
            instr_list = [goal]
            outcomes_list = ["Goal is achieved successfully."]
            rules_list = []
        else:
            instr_list = goal or []
            outcomes_list = expected_outcomes or []
            rules_list = security_rules or []

        # Redact input variables
        if gui_elements:
            gui_elements = redact_elements(gui_elements)
        if text_history:
            text_history = [redact_text(act) for act in text_history]

        caps_description_str = "\n".join(
            f"   - {cap.value}: {CAPABILITY_SCHEMAS.get(cap, '{}')}"
            for cap in CapabilityType
        )

        prompt_text = f"""You are a closed-loop mobile E2E testing agent performing QA validation on a mobile app.
Your task is to execute the following E2E test scenario instructions and verify all expected outcomes and security compliance rules.

### Test Scenario Instructions
{chr(10).join(f"- {step}" for step in instr_list)}

### Expected Outcomes / Assertions
{chr(10).join(f"- {outcome}" for outcome in outcomes_list)}

### Custom Security Rules to Enforce
{chr(10).join(f"- {rule}" for rule in rules_list) if rules_list else "None specified."}

### Current UI Elements Detected (YOLO/OCR)
{self._format_elements_for_prompt(gui_elements) if gui_elements else "None detected."}

### History of Executed Actions
{chr(10).join(f"- {act}" for act in text_history) if text_history else "No actions executed yet."}
"""

        if loop_warning:
            prompt_text += f"""
### LOOP DETECTION WARNING
{loop_warning}
"""

        if drift_warning:
            prompt_text += f"""
### CONTEXT DRIFT WARNING
{drift_warning}
"""

        prompt_text += f"""
### QA Auditing Instructions
You must inspect the visual screenshots provided and audit the screen state for layout, logic, and security defects:
1. **Visual/Layout Bugs**: Scan the screen for visual issues, including diagonal black-and-yellow warning stripes indicating layout render overflows, clipped texts, overlapping buttons, misaligned headers, or empty image containers.
2. **Security Vulnerabilities**: Scan for plain-text password inputs, unmasked private PINs, exposed authentication hashes, credit card digits, or accessible admin/debug routes.
3. **Dynamic Screen Assertions**: Generate context-specific screen assertions on the fly for the current screen layout (e.g., "Email input field is present", "Primary action button is visible and enabled", "No visual layout clipping"). Verify whether these dynamic assertions pass or fail on the current screen.
4. **Dynamic Rule Verifications**: For each pre-defined expected outcome, custom security rule, and dynamic screen assertion, determine if it has been "passed" or "failed" on the current screen, or remains "untested".
5. **Scenario Feasibility**: Verify if the test scenario instructions are valid and feasible to perform on the current screen. If instructions require interacting with elements, fields, or buttons that do not exist (e.g., trying to input a password on a login screen with no password textfield), flag the scenario as infeasible.

### Allowed Action Schema and Types
Each action you return in the `action.actions` list must have a `type` matching one of the following string literals:
- "tap": Taps at screen coordinates. Required fields: `type` (literal "tap"), `coordinates` (with x, y integers), and `reason` (str).
- "type": Types text into a text field. Required fields: `type` (literal "type"), `text` (str), `coordinates` (with x, y integers), and `reason` (str).
- "clear": Clears the content of a text field. Required fields: `type` (literal "clear"), `coordinates` (with x, y integers), and `reason` (str).
- "double_tap": Double-taps at coordinates. Required fields: `type` (literal "double_tap"), `coordinates` (with x, y integers), and `reason` (str).
- "long_press": Long presses coordinates. Required fields: `type` (literal "long_press"), `duration` (float seconds), `coordinates` (with x, y integers), and `reason` (str).
- "drag_and_drop": Drags from source to destination. Required fields: `type` (literal "drag_and_drop"), `source_x` (int), `source_y` (int), `destination_x` (int), `destination_y` (int), and `reason` (str).
- "key_event": Triggers a key event. Required fields: `type` (literal "key_event"), `key` (int keycode, e.g., 4=back, 3=home, 66=enter, 67=backspace), and `reason` (str).
- "swipe": Swipes from start to end. Required fields: `type` (literal "swipe"), `start_x` (int), `start_y` (int), `end_x` (int), `end_y` (int), and `reason` (str).
- "capability": Triggers system capability controls. Required fields: `type` (literal "capability"), `capability` (str), `parameters` (dict), and `reason` (str).

CRITICAL CONSTRAINTS:
1. Do NOT use invalid types like "click" or "send_keys" or "input". You MUST use "tap" for tapping/clicking and "type" for typing text.
2. For typing text, you MUST specify both the `text` string AND the `coordinates` (x, y) of the text field where the text should be typed.

### Response Instructions
1. Identify the descriptive name of the current screen/page (e.g., "Login View", "Product Catalog").
2. Assess all QA issues and populate `detected_issues`.
3. Assess expected outcomes, custom security rules, and dynamically generated screen assertions, and populate `rule_verifications` with all of them.
4. Determine if the scenario is feasible. If it is impossible to satisfy the steps due to missing UI components or layout mismatch, set `is_scenario_feasible = False`, fill `infeasibility_reason` with the details, and set `is_done = True` and `action = None`.
5. Determine if the scenario is done (either all expected outcomes have been successfully verified, or a critical crash/failure terminates the test). If so, set `is_done = True` and `action = None`.
6. If not done and the scenario is feasible, plan the single next action to execute. You must output EXACTLY one action in `action.actions` list.
7. If the step or goal requires system level control, return a CAPABILITY action. Specify 'capability' and its 'parameters' dict:
{caps_description_str}
8. If the next planned action is expected to navigate outside of the System Under Test (SUT) application (e.g., opening a browser link, launching a system setting, or interacting with a system dialog), set the `external_navigation` field of the `ActionPlan` to `True`. Otherwise, keep it `False`.
"""


        if self.use_multimodal_vision:
            prompt_text += """
6. Prefer using the center coordinates of the detected UI elements. However, since multimodal override is ENABLED, if you visually detect a critical element that was missed by YOLO/OCR, or if the bounding box center is incorrect, you may specify custom coordinate overrides (x, y) based on your direct visual inspection of the screenshot.
"""
        else:
            prompt_text += """
6. You MUST strictly select and target the center coordinates of the detected UI elements listed above. Do not specify coordinates outside of the detected element bounding boxes.
"""

        message = MultiPartMessage()
        
        # Add visual history in chronological order
        for idx, img_bytes in enumerate(visual_history or []):
            message.add_text(f"Screenshot from step {idx + 1}:")
            message.add_image(img_bytes)
            
        # Add current screenshot
        message.add_text("Current screenshot (newest):")
        message.add_image(current_image_bytes)
        message.add_text(prompt_text)

        logger.info("Querying planner for next step with QA auditing...")
        response: AgentStepResponse = self.llm.generate_response([message], AgentStepResponse)

        # Redact sensitive values from response content
        response.reasoning = redact_text(response.reasoning)
        for issue in response.detected_issues:
            issue.description = redact_text(issue.description)
        for verify in response.rule_verifications:
            verify.reasoning = redact_text(verify.reasoning)

        return response

